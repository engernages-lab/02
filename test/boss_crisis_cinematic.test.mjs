// V1.3-B.6.5 动态危机电影化配置/视觉引擎单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const X = L('src/game/bossCrisisCinematicConfig.ts');
const D = L('src/game/events/unknownIntrusion.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const kinds = ['warning', 'detection', 'identification', 'escalation', 'impact', 'response', 'resolution', 'recovery'];
const stages = X.CRISIS_CINEMATIC_STAGES;
console.log('=== 1. 配置 / 阶段 ===');
ok(stages.length === 8, '八阶段配置');
ok(kinds.every((k, i) => stages[i].kind === k), '阶段顺序 warning→recovery');
ok(stages.every(s => s.durationMs > 0 && !!s.kicker && !!s.label && !!s.text), '阶段时长/文案完整');
ok(stages[0].durationMs === D.UNKNOWN_INTRUSION_DEF.presentDurationMs, 'Warning 使用真实 presenting 时长');
ok(X.crisisCinematicStageFor('impact').kind === 'impact', 'stage lookup');
ok(X.crisisCinematicStageFor('nope').kind === 'warning', '非法 stage fallback');
ok(X.crisisStageAtElapsed('warning', 0).kind === 'warning', 'Warning 前段');
ok(X.crisisStageAtElapsed('warning', 800).kind === 'detection', 'Warning 后段 → Detection');
ok(X.crisisStageAtElapsed('warning', 9999).kind === 'detection', '超长 elapsed fallback');
ok(X.crisisStageAtElapsed('impact', 0).kind === 'impact', '非 warning 阶段不拆分');
console.log('=== 2. 主题 ===');
for (const k of kinds) {
  const t = X.crisisCinematicThemeFor(k, 'unknown-intrusion');
  ok(/^#[0-9a-fA-F]{3,8}$/.test(t.primary) && /^#[0-9a-fA-F]{3,8}$/.test(t.secondary) && /^#[0-9a-fA-F]{3,8}$/.test(t.danger), '主题合法：' + k);
}
ok(X.crisisCinematicThemeFor('warning', 'unknown-intrusion').primary !== X.crisisCinematicThemeFor('resolution', 'unknown-intrusion').primary, '阶段主题不同');
const unknownTheme = X.crisisCinematicThemeFor('warning', 'not-registered');
ok(unknownTheme.primary === '#FF5B64', '未知危机主题 fallback');
ok(X.crisisEventTitle('unknown-intrusion') === '未知入侵', '真实事件标题');
ok(X.crisisEventTitle('mystery') === 'SYSTEM ANOMALY', '未知事件标题 fallback');
ok(X.crisisStatusLabel('presenting') === '检测中' && X.crisisStatusLabel('active') === '隔离中' && X.crisisStatusLabel('completed') === '已结束', '真实状态文案');
console.log('=== 3. Snapshot / Payload ===');
ok(X.crisisSnapshotOf(null, 'b1') === null, '空事件安全');
const state = {
  id: 'unknown-intrusion@100-1', defId: 'unknown-intrusion', status: 'active', priority: 100,
  startedAt: 100, activateAt: 1700, deadlineAt: 46700, endedAt: null, result: null, reason: null,
  data: { step: 1, missesLeft: 2 },
};
const snap = X.crisisSnapshotOf(state, 'battle-x');
ok(snap.id === state.id && snap.defId === 'unknown-intrusion', '真实 id/defId');
ok(snap.status === 'active' && snap.step === 1 && snap.missesLeft === 2, '真实 status/data');
ok(snap.battleId === 'battle-x' && snap.activateAt === 1700 && snap.deadlineAt === 46700, '真实时间/附加 battleId');
ok(X.crisisSnapshotOf({ ...state, defId: 'generic-crisis', data: { step: 99, missesLeft: -3 } }, 'b').missesLeft === 0, '通用事件数据夹紧');
console.log('=== 4. 真实状态差异 → 视觉阶段 ===');
const base = { id: 'e1', defId: 'unknown-intrusion', status: 'presenting', result: null, step: 0, missesLeft: 3, startedAt: 0, activateAt: 1600, deadlineAt: 46600, reason: null, battleId: 'b1' };
ok(X.crisisTransitions(null, base)[0].kind === 'warning', '新事件 → Warning');
ok(X.crisisTransitions(base, { ...base })[0] === undefined, '无变化不重复演出');
ok(X.crisisTransitions(base, { ...base, status: 'active' })[0].kind === 'identification', 'presenting→active → Identification');
const step1 = { ...base, status: 'active', step: 1 };
ok(X.crisisTransitions({ ...base, status: 'active' }, step1)[0].kind === 'response', '真实 step → Response');
const miss = { ...base, status: 'active', missesLeft: 2 };
ok(X.crisisTransitions({ ...base, status: 'active' }, miss)[0].kind === 'impact', '真实 miss → Impact');
const done = { ...base, status: 'completed', result: 'completed' };
ok(X.crisisTransitions({ ...base, status: 'active' }, done)[0].kind === 'resolution', 'completed → Resolution');
const canc = { ...base, status: 'completed', result: 'cancelled' };
ok(X.crisisTransitions({ ...base, status: 'active' }, canc)[0].kind === 'recovery', 'cancelled → Recovery');
const rec = { ...base, status: 'completed', result: 'recovered' };
ok(X.crisisTransitions({ ...base, status: 'active' }, rec)[0].kind === 'recovery', 'recovered → Recovery');
const timeout = { ...base, status: 'resolving', result: 'timeout' };
const tT = X.crisisTransitions({ ...base, status: 'active' }, timeout);
ok(tT.length === 2 && tT[0].kind === 'impact' && tT[1].kind === 'recovery', 'timeout → Impact + Recovery');
const dismissed = X.crisisTransitions({ ...base, status: 'completed', result: 'completed' }, null);
ok(dismissed[0].kind === 'recovery', '真实 dismiss → Recovery');
ok(X.crisisTransitions(null, null).length === 0, 'null→null 无演出');
ok(X.crisisTransitions(base, { ...base, id: 'e2', battleId: 'b2' })[0].kind === 'warning', '不同事件 → 新 Warning');
ok(X.crisisTransitions(base, { ...base, battleId: 'b2' }).length === 0, '不同 battleId 拒绝');
ok(X.crisisTransitions({ ...base, status: 'active' }, { ...base, status: 'active', step: 1 }).every(t => t.kind !== 'escalation'), '真实流程不虚构 Escalation');
console.log('=== 5. 去重 / View ===');
const k1 = X.crisisCinematicDedupeKey('b1', 'e1', 'impact', 'miss:2');
ok(k1 === 'b1:e1:impact:miss:2', 'battleId:eventId:kind:marker');
ok(k1 !== X.crisisCinematicDedupeKey('b2', 'e1', 'impact', 'miss:2'), '不同战斗不冲突');
ok(k1 !== X.crisisCinematicDedupeKey('b1', 'e1', 'response', 'miss:2'), '不同阶段不冲突');
ok(X.crisisCinematicDedupeKey(null, null, 'warning', null) === '::warning:', '空值安全');
const view = X.crisisViewFor(snap, { kind: 'identification', marker: 'active', detail: '真实隔离序列' }, 1000, 'REAL');
ok(view.eventId === snap.id && view.battleId === 'battle-x' && view.title === '未知入侵', 'View 真实字段');
ok(view.kind === 'identification' && view.stage === 'identification' && view.expiresAt > view.startedAt, 'View 阶段/时长');
ok(view.source === 'REAL' && !!view.theme.primary, 'View source/theme');
console.log('=== 6. 视觉注册 / 优先级 ===');
const def = C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'];
ok(!!def, '危机演出注册');
ok(def.priority === C.VISUAL_PRIORITY.crisis, '危机演出 P2');
ok(def.queueable === false, '危机演出不排队');
ok(def.interruptible === true, '危机可被 P1/P0 中断');
ok(def.layer === 'cinematic', 'cinematic 层');
ok(C.VISUAL_PRIORITY.phase < C.VISUAL_PRIORITY.crisis && C.VISUAL_PRIORITY.crisis < C.VISUAL_PRIORITY.weakness, 'P1 < P2 < P3');
console.log('=== 7. 生命周期 / 抢占 / 清理 ===');
let st = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-warning'], 0, { intensity: 'HIGH' }).state;
st = E.triggerVisualEffect(st, C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 5, { intensity: 'HIGH' }).state;
const crisis = E.triggerVisualEffect(st, C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 10, { intensity: 'HIGH' });
ok(crisis.accepted && crisis.state.active.some(e => e.effectId === 'boss-crisis-cinematic'), '危机演出启动');
ok(crisis.state.completed.some(e => e.effectId === 'boss-attack-warning' && e.status === 'interrupted'), '危机抢占攻击');
ok(crisis.state.completed.some(e => e.effectId === 'boss-weakness-cinematic' && e.status === 'interrupted'), '危机抢占弱点');
const dup = E.triggerVisualEffect(crisis.state, C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 20);
ok(!dup.accepted && dup.reason === 'duplicate', '重复危机演出拒绝');
const phase = E.triggerVisualEffect(crisis.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 30);
ok(phase.state.completed.some(e => e.effectId === 'boss-crisis-cinematic'), 'Phase P1 抢占危机');
const terminal = E.triggerVisualEffect(phase.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 40);
ok(terminal.state.active.some(e => e.effectId === 'boss-terminal-flash'), 'Terminal P0 抢占');
const cleaned = E.cleanupAllVisualEffects(terminal.state, 50);
ok(cleaned.active.length === 0 && cleaned.queued.length === 0, 'Cleanup 无残留');
ok(E.cleanupAllVisualEffects(cleaned, 60) === cleaned, '重复 cleanup 幂等');
console.log('=== 8. 强度 / 性能 ===');
ok(E.particleBudget('LOW', 'full', false) === 0, 'LOW 无粒子');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, 'CINEMATIC 不超上限');
const reduced = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 0, { intensity: 'HIGH', reducedMotion: true }).state;
ok(reduced.active[0].intensity < 0.5, 'Reduced Motion 降低危机强度');
ok(E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 0).state.active.length <= C.MAX_ACTIVE_EFFECTS, '活动效果上限');
ok(E.evaluateVisualPerformance(20, 'full', 0, 5000) === 'minimal', '性能降级');
ok(C.VISUAL_LAYER_Z.terminal > C.VISUAL_LAYER_Z.cinematic, '终结层级高于危机');
let many = E.createVisualRuntime(0);
for (let i = 0; i < 12; i++) many = E.triggerVisualEffect(many, { ...def, effectId: 'crisis-' + i, priority: C.VISUAL_PRIORITY.ambient }, i).state;
ok(many.queued.length <= C.MAX_QUEUED_EFFECTS, '队列上限');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
