// V1.3-D 探索集成：真实区域/挑战入口/存档/幂等
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const X = L('src/game/explorationCore.ts');
const M = L('src/game/miraCore.ts');
const Save = L('src/services/save.ts');
const Levels = L('src/game/levels.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 8000;
const allServers = Levels.SERVERS.map(s => s.id);
let st = X.defaultExplorationState(NOW);
console.log('=== 1. 真实区域解锁 ===');
ok(X.explorationRegionDefs().length === Levels.SERVERS.length, '区域来自真实 SERVERS');
ok(X.regionUnlocked('training', ['training']), '训练区域真实解锁');
ok(!X.regionUnlocked('syntax', ['training']), '未解锁服务器阻止进入');
ok(X.regionStatus(st, 'syntax', ['training']) === 'LOCKED', '锁定区域状态');
ok(X.nodeState(st, 'terminal:syntax') === 'available', '节点定义仍存在但不进入');
console.log('=== 2. 信号 → 遗迹 → 隐藏 ===');
let d = X.discoverRegion(st, 'training', NOW); st = d.state;
let r = X.completeExploreNode(st, 'training', 'signal:training', ['training'], NOW + 1); st = r.state;
ok(r.changed && r.node?.kind === 'signal', '真实信号事件');
r = X.completeExploreNode(st, 'training', 'ruin:training', ['training'], NOW + 2); st = r.state;
ok(r.changed && st.ruins['ruin:training'], '真实遗迹事件');
ok(!X.hiddenAvailable(st, 'training'), '核心未完成隐藏不可见');
const start = X.startTerminalChallenge(st, 'training', 'terminal:training', NOW + 3);
ok(start.pending?.levelId === 'tut-1' && start.node?.kind === 'terminal', '真实终端 → tut-1');
ok(!X.completeTerminalChallenge(start.state, 'tut-1', false, NOW + 4).changed, '失败不完成探索');
const win = X.completeTerminalChallenge(start.state, 'tut-1', true, NOW + 5); st = win.state;
ok(win.changed && win.credits === 10, '真实挑战成功完成探索');
ok(X.hiddenAvailable(st, 'training'), '区域完成 → 隐藏信号出现');
const hidden = X.completeExploreNode(st, 'training', 'hidden:training:echo', ['training'], NOW + 6); st = hidden.state;
ok(hidden.changed && st.hidden['hidden:training:echo'], '隐藏事件真实完成');
console.log('=== 3. 第二个遗迹 / 多区域 ===');
let st2 = X.defaultExplorationState(NOW);
const syntax = X.completeExploreNode(st2, 'syntax', 'ruin:syntax', allServers, NOW + 7);
ok(syntax.changed && syntax.node?.name === '被封锁的记忆节点', '第二遗迹：被封锁记忆节点');
ok(!X.completeExploreNode(syntax.state, 'syntax', 'ruin:syntax', allServers, NOW + 8).changed, '第二遗迹幂等');
console.log('=== 4. 奖励 / 档案幂等 ===');
ok(st.rewardsClaimed.length === 4, '四类节点奖励记录');
ok(new Set(st.rewardsClaimed).size === st.rewardsClaimed.length, '奖励 ID 无重复');
ok(st.archive.length === 4, '探索档案四条');
const again = X.completeExploreNode(st, 'training', 'signal:training', ['training'], NOW + 9);
ok(!again.changed && again.credits === 0, '完整状态重复调查无奖励');
console.log('=== 5. MIRA 联动数据 ===');
let mira = M.defaultMiraState(NOW);
const ma = M.miraAward(mira, { eventId: 'mira:exploration:signal:training', xp: 4, source: 'exploration', now: NOW });
mira = ma.state;
ok(mira.exp === 4, '探索 → MIRA 经验');
const ms = M.miraSceneLine('enter-region', mira, {}, NOW + 10);
ok(ms.changed && ms.text.includes('异常数据流'), '探索 → MIRA 区域对白');
console.log('=== 6. 存档 / 业务只读 ===');
let p = Save.defaultState();
p = { ...p, progress: { ...p.progress, exploration: st }, mira };
const base = JSON.stringify({ level: p.level, exp: p.exp, rewards: p.rewards, stats: p.progress.bossBattleStats, mira: p.mira });
const norm = Save.normalizePlayerState(p, 10);
const after = JSON.stringify({ level: norm.level, exp: norm.exp, rewards: norm.rewards, stats: norm.progress.bossBattleStats, mira: norm.mira });
ok(after === base, '探索不修改玩家/奖励/统计/MIRA 业务字段');
ok(JSON.stringify(norm.progress.exploration) === JSON.stringify(st), '探索状态 Save/读取保持');
ok(Save.SAVE_VERSION === 10, 'SAVE_VERSION 10');
const old = { ...norm, progress: { ...norm.progress, exploration: undefined } };
ok(!!Save.normalizePlayerState(old, 10).progress.exploration, '旧存档安全补齐探索');
console.log('=== 7. 进度计算 ===');
const totals = X.explorationTotals(st, ['training']);
ok(totals.regionsUnlocked === 1 && totals.regionsCompleted === 1, '已完成区域统计');
ok(totals.nodesCompleted === 3 && totals.nodesTotal === 21, '已解锁/全部节点统计');
ok(totals.hiddenFound === 1, '隐藏发现统计');
ok(X.regionProgress(st, 'training').pct === 100, '区域真实百分比');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
