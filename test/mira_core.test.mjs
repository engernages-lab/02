// V1.3-C MIRA 核心逻辑单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const M = L('src/game/miraCore.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 1000;
console.log('=== 1. 默认 / 等级 / 阶段 ===');
const fresh = M.defaultMiraState(NOW);
ok(fresh.level === 1 && fresh.exp === 0 && fresh.stage === 'initial', '默认 Lv1 / 初始连接');
ok(fresh.memories && Object.keys(fresh.memories).length === 0, '默认无记忆');
ok(M.miraLevelForExp(0) === 1 && M.miraLevelForExp(29) === 1, 'Lv1 阈值');
ok(M.miraLevelForExp(30) === 2 && M.miraLevelForExp(79) === 2, 'Lv2 阈值');
ok(M.miraLevelForExp(1200) === 10 && M.miraLevelForExp(99999) === 10, 'Lv10 封顶');
ok(M.miraStageForLevel(1) === 'initial' && M.miraStageForLevel(3) === 'sync' && M.miraStageForLevel(6) === 'deep' && M.miraStageForLevel(9) === 'coop', '成长阶段');
ok(M.MIRA_STAGE_LABEL.initial === '初始连接' && M.MIRA_STAGE_LABEL.coop === '高级协同', '阶段中文');
console.log('=== 2. 经验 / 升级 / 幂等 ===');
let s = fresh;
let r = M.miraAward(s, { eventId: 'evt:1', xp: 20, source: 'challenge', now: NOW });
ok(r.changed && r.state.exp === 20 && !r.levelUp, '获得经验不升级');
const dup = M.miraAward(r.state, { eventId: 'evt:1', xp: 20, source: 'challenge', now: NOW + 1 });
ok(!dup.changed && dup.state.exp === 20, '同一事件 ID 不重复经验');
r = M.miraAward(r.state, { eventId: 'evt:2', xp: 20, source: 'challenge', now: NOW + 2 });
ok(r.levelUp && r.state.level === 2 && r.fromLevel === 1 && r.toLevel === 2, '30 XP 升级 Lv2');
ok(r.state.stage === 'initial', 'Lv2 仍初始连接');
r = M.miraAward(r.state, { eventId: 'evt:3', xp: 10000, source: 'test', now: NOW + 3 });
ok(r.state.exp === 540 && r.state.level === 7, '单次经验上限 500');
const maxState = M.normalizeMiraState({ exp: 1200 }, NOW);
ok(maxState.level === 10 && maxState.stage === 'coop', '满级 Lv10/高级协同');
const bad = M.miraAward(r.state, { eventId: '', xp: 10, source: 'bad', now: NOW + 4 });
ok(!bad.changed, '空事件 ID 拒绝');
console.log('=== 3. 记忆解锁 / 已读 ===');
let m = fresh;
const u = M.miraUnlockMemory(m, 'mira-first-contact', NOW);
ok(u.changed && u.state.memories['mira-first-contact'] && !u.state.memories['mira-first-contact'].read, '记忆解锁未读');
ok(u.memory && u.memory.name === '初始相遇', '记忆真实定义');
const u2 = M.miraUnlockMemory(u.state, 'mira-first-contact', NOW + 1);
ok(!u2.changed, '重复解锁拒绝');
const read = M.miraMarkRead(u.state, 'mira-first-contact', NOW + 2);
ok(read.changed && read.state.memories['mira-first-contact'].read, '记忆标记已读');
ok(!M.miraMarkRead(read.state, 'mira-first-contact').changed, '重复已读幂等');
ok(M.MIRA_MEMORY_DEFS.length === 6 && M.MIRA_MEMORY_DEFS.every(x => !!x.name && !!x.condition && !!x.mira), '六类记忆定义完整');
ok(M.miraMemoryById('mira-boss-victory')?.type === 'boss', 'Boss 记忆类型');
console.log('=== 4. Award 带记忆 ===');
const aw = M.miraAward(fresh, { eventId: 'fix:1', xp: 10, source: 'challenge', memoryId: 'mira-first-fix', now: NOW });
ok(aw.state.memories['mira-first-fix'] && aw.memoryUnlocked?.id === 'mira-first-fix', '事件同时解锁记忆');
ok(aw.state.exp === 10, '事件经验');
console.log('=== 5. 进度 ===');
const prog = M.miraLevelProgress({ ...fresh, exp: 45, level: 2 });
ok(prog.level === 2 && prog.floor === 30 && prog.next === 80 && prog.pct === 30, '等级进度计算', JSON.stringify(prog));
const maxProg = M.miraLevelProgress({ ...fresh, exp: 99999, level: 10 });
ok(maxProg.pct === 100, '满级进度');
console.log('=== 6. 场景反馈 / 去重 ===');
const line1 = M.miraSceneLine('repair-success', fresh, {}, NOW);
ok(line1.changed && line1.text.length > 0 && line1.state.interactions.length === 1, '场景反馈写入交互');
const line2 = M.miraSceneLine('repair-success', line1.state, {}, NOW + 100);
ok(!line2.changed, '同场景冷却内不刷屏');
const line3 = M.miraSceneLine('repair-success', line1.state, {}, NOW + 7000);
ok(line3.changed && line3.state.interactions.length === 2, '冷却后记录新交互');
ok(line3.state.interactions.length <= 30, '交互记录有界');
ok(M.miraSceneLine('boss-enter', fresh, {}, NOW).text.includes('Boss') || M.miraSceneLine('boss-enter', fresh, {}, NOW).text.includes('高危'), 'Boss 进入对白匹配');
console.log('=== 7. 风险规则 ===');
const r0 = M.miraRiskFor({});
ok(r0[0].level === 'low', '默认低风险');
const r1 = M.miraRiskFor({ consciousness: 20 });
ok(r1.some(x => x.level === 'high' && x.text.includes('意识')), '低意识高风险');
const r2 = M.miraRiskFor({ crisis: true, attackWarning: true });
ok(r2.filter(x => x.level === 'high').length >= 2, '危机/预警高风险');
const r3 = M.miraRiskFor({ consecutiveFails: 3 });
ok(r3.some(x => x.text.includes('连续失败')), '连续失败提示');
const r4 = M.miraRiskFor({ bossPhase: 2 });
ok(r4.some(x => x.text.includes('Boss')), 'Boss 高阶段提示');
console.log('=== 8. 自愈 / 存档兼容 ===');
const corrupt = M.normalizeMiraState({ exp: -5, level: 99, memories: { bad: {}, 'mira-first-fix': { unlockedAt: 'x', read: true } }, eventLog: ['a', 'a', 3], interactions: [{ text: 'ok', at: 'x' }] }, NOW);
ok(corrupt.exp === 0 && corrupt.level === 1, '损坏经验/等级自愈');
ok(corrupt.eventLog.length === 1 && corrupt.eventLog[0] === 'a', '事件日志去重/清洗');
ok(corrupt.memories['mira-first-fix'] && corrupt.memories['mira-first-fix'].read === true && !corrupt.memories.bad, '记忆清洗');
ok(corrupt.interactions.length === 1 && typeof corrupt.interactions[0].at === 'number', '交互清洗');
ok(M.normalizeMiraState(null).level === 1, '缺失 MIRA 默认初始化');
const def = Save.defaultState();
ok(!!def.mira && def.mira.level === 1, 'defaultState 包含 MIRA');
ok(Save.SAVE_VERSION === 10, '存档版本保持 10');
const noMira = { ...def, mira: undefined };
const normalized = Save.normalizePlayerState(noMira, 10);
ok(!!normalized.mira && normalized.mira.level === 1, '旧存档缺少 MIRA 安全补齐');
ok(normalized.level === def.level && normalized.exp === def.exp, '补齐 MIRA 不影响玩家等级/经验');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
