// V1.3-B.6.3 集成：真实 B.1 Phase Transition → 视觉层隔离
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const P = L('src/game/bossPhaseTransitionCinematicConfig.ts');
const Phase = L('src/game/bossPhaseEngine.ts');
const Plans = L('src/game/bossPhasePlans.ts');
const Attack = L('src/game/bossAttackEngine.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 300000;
const plan = Plans.buildBossPhasePlan('gate-01', 'easy');
let run = Phase.createBossPhaseRun(plan, NOW, { battleId: 'battle-phase-cine', hp: plan.totalHp });
run = Phase.prepareBattle(run, NOW).run;
run = Phase.activateBattle(run, plan, NOW).run;
const transition = Phase.evaluatePhaseTransition(run, plan, { hp: Math.floor(plan.totalHp * 0.5), completedChallenges: [] }, NOW + 1000);
const event = transition.events.find(e => e.type === 'BOSS_PHASE_TRANSITION');
const beforeRun = JSON.stringify(transition.run);
const beforeRunInput = JSON.stringify(run);
console.log('=== 1. 真实 Phase Transition 事件 ===');
ok(transition.ok && !!event, '真实阶段转换事件');
ok(event.battleId === 'battle-phase-cine' && event.payload.transitionId === transition.run.transition.id, 'battleId/transitionId');
ok(event.payload.fromIndex === 0 && event.payload.toIndex >= 1, 'from/to index');
ok(event.payload.toPhaseName === plan.phases[transition.run.transition.toIndex].phaseName, '真实 toPhaseName');
ok(event.phaseId === plan.phases[transition.run.transition.toIndex].phaseId, 'phaseId 为真实新阶段');
ok(typeof event.payload.transitionId === 'string' && event.payload.transitionId.length > 0, 'transitionId 非空');
const theme = P.phaseTransitionThemeFor(event.payload.toIndex);
ok(!!theme.primary && !!theme.secondary, '阶段主题存在');
ok(P.phaseRevealNumber(event.payload.toIndex) === 'PHASE 0' + (event.payload.toIndex + 1), 'Phase 编号真实');
console.log('=== 2. 视觉触发不改变阶段/攻击 ===');
let visual = E.createVisualRuntime(NOW);
visual = E.triggerVisualEffect(visual, C.BOSS_VISUAL_EFFECTS['boss-axis'] || C.BOSS_VISUAL_EFFECTS['boss-attack-warning'], NOW, { intensity: 'HIGH' }).state;
const pv = E.triggerVisualEffect(visual, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], NOW + 1010, { intensity: 'HIGH' });
visual = pv.state;
ok(pv.accepted && visual.active.some(e => e.effectId === 'boss-phase-cinematic'), '阶段演出启动');
ok(JSON.stringify(run) === beforeRunInput, '视觉不修改原 run');
ok(JSON.stringify(transition.run) === beforeRun, '视觉不修改 transition run');
ok(transition.run.status === 'phase_transition', '真实状态仍为 phase_transition');
const attack = Attack.createBossAttackState('battle-phase-cine', 'gate-01', plan.phases[0].phaseId, 0, NOW);
const attackBefore = JSON.stringify(attack);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 0);
ok(JSON.stringify(attack) === attackBefore, '视觉不修改攻击状态');
console.log('=== 3. 攻击视觉冲突 / 终结 ===');
let attackVisual = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-release'], 0).state;
const phaseVisual = E.triggerVisualEffect(attackVisual, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 10);
ok(phaseVisual.state.completed.some(e => e.effectId === 'boss-attack-release'), '阶段演出中断攻击 release');
const terminal = E.triggerVisualEffect(phaseVisual.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 20);
ok(terminal.state.active.some(e => e.effectId === 'boss-terminal-flash'), 'Victory P0 抢占阶段');
ok(terminal.state.completed.some(e => e.effectId === 'boss-phase-cinematic'), '终结清理阶段');
const cleaned = E.cleanupAllVisualEffects(terminal.state, 30);
ok(cleaned.active.length === 0 && cleaned.queued.length === 0, '终结/清理无残留');
console.log('=== 4. 数据 / 存档 / 主题 ===');
ok(Save.SAVE_VERSION === 10, '存档版本 v10');
const p = Save.defaultState();
const pBefore = JSON.stringify(p);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 0);
ok(JSON.stringify(p) === pBefore, '视觉不改存档/经济/成就');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, '阶段演出遵守粒子上限');
ok(C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'].priority === C.VISUAL_PRIORITY.phase, '阶段演出 P1');
ok(P.phaseStageForElapsed(0).stage === 'pre' && P.phaseStageForElapsed(2000).stage === 'reveal', '阶段流程时间线');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
