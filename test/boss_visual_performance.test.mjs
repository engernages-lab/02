// V1.3-B.6.7 视觉性能 / 无障碍配置与控制器单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const modes = ['AUTO', 'NORMAL', 'REDUCED', 'LOW', 'CRITICAL'];
console.log('=== 1. Performance Mode 配置 ===');
ok(modes.every(m => C.normalizePerformanceMode(m) === m), '合法模式保留');
ok(C.normalizePerformanceMode('bad') === 'AUTO' && C.normalizePerformanceMode(null) === 'AUTO', '非法模式 fallback AUTO');
ok(C.DEFAULT_PERFORMANCE_MODE === 'AUTO', '默认 AUTO');
ok(C.maxDprForMode('NORMAL') === 2 && C.maxDprForMode('REDUCED') === 1.5, 'DPR NORMAL/REDUCED');
ok(C.maxDprForMode('LOW') === 1 && C.maxDprForMode('CRITICAL') === 1, 'DPR LOW/CRITICAL');
ok(C.performanceLevelForMode('NORMAL') === 'full', 'NORMAL → full');
ok(C.performanceLevelForMode('REDUCED') === 'reduced', 'REDUCED → reduced');
ok(C.performanceLevelForMode('LOW') === 'minimal' && C.performanceLevelForMode('CRITICAL') === 'minimal', 'LOW/CRITICAL → minimal');
ok(C.activePerformanceMode('AUTO', 'REDUCED') === 'REDUCED', 'AUTO 使用实际模式');
ok(C.activePerformanceMode('LOW', 'NORMAL') === 'LOW', '强制模式优先');
ok(C.modeSeverity('NORMAL') < C.modeSeverity('REDUCED') && C.modeSeverity('REDUCED') < C.modeSeverity('LOW') && C.modeSeverity('LOW') < C.modeSeverity('CRITICAL'), '严重度排序');
console.log('=== 2. FPS 平滑 / 目标模式 ===');
ok(E.smoothFps(60, 30) === 52.5, 'FPS 平滑 alpha=0.25', String(E.smoothFps(60, 30)));
ok(E.smoothFps(0, 45) === 45, '初始平滑样本');
ok(E.smoothFps(50, NaN) === 50, '非法样本安全');
ok(E.performanceTargetForFps(60) === 'NORMAL' && E.performanceTargetForFps(55) === 'NORMAL', '>=55 NORMAL');
ok(E.performanceTargetForFps(54) === 'REDUCED' && E.performanceTargetForFps(45) === 'REDUCED', '45–54 REDUCED');
ok(E.performanceTargetForFps(44) === 'LOW' && E.performanceTargetForFps(30) === 'LOW', '30–44 LOW');
ok(E.performanceTargetForFps(29) === 'CRITICAL' && E.performanceTargetForFps(1) === 'CRITICAL', '<30 CRITICAL');
console.log('=== 3. 动态降级 / 恢复滞后 ===');
const base = { mode: 'NORMAL', smoothedFps: 60, lastChangeAt: 0, stableSince: 0, reason: 'init' };
let r = E.nextPerformanceMode(base, 'AUTO', 50, 1000);
ok(!r.changed && r.state.mode === 'NORMAL', '首次低 FPS 不立即降级');
for (let i = 2; i <= 5; i++) r = E.nextPerformanceMode(r.state, 'AUTO', 50, i * 1000);
ok(!r.changed, '平滑确认期内不误降');
for (let i = 6; i <= 9; i++) r = E.nextPerformanceMode(r.state, 'AUTO', 50, i * 1000);
ok(r.state.mode === 'REDUCED', '持续低 FPS → REDUCED');
const afterChange = E.nextPerformanceMode(r.state, 'AUTO', 50, 10000);
ok(!afterChange.changed && afterChange.state.mode === 'REDUCED', '切换后冷却期不反复');
let low = { mode: 'NORMAL', smoothedFps: 60, lastChangeAt: 0, stableSince: 0, reason: '' };
for (let i = 1; i <= 12; i++) low = E.nextPerformanceMode(low, 'AUTO', 25, i * 1000).state;
ok(low.mode === 'CRITICAL', '25fps 持续 → CRITICAL');
let rec = { mode: 'CRITICAL', smoothedFps: 25, lastChangeAt: 0, stableSince: 0, reason: '' };
for (let i = 1; i <= 3; i++) rec = E.nextPerformanceMode(rec, 'AUTO', 60, i * 1000).state;
ok(rec.mode === 'CRITICAL', '恢复需稳定窗口');
for (let i = 4; i <= 10; i++) rec = E.nextPerformanceMode(rec, 'AUTO', 60, i * 1000).state;
ok(rec.mode === 'LOW', '稳定恢复一级 CRITICAL→LOW');
const rec2 = E.nextPerformanceMode(rec, 'AUTO', 60, 7000);
ok(!rec2.changed, '恢复切换后有冷却');
const forced = E.nextPerformanceMode({ ...base }, 'LOW', 60, 1000);
ok(forced.changed && forced.state.mode === 'LOW' && forced.state.reason === 'forced:LOW', '强制模式立即生效');
console.log('=== 4. 粒子 / Budget ===');
ok(E.particleBudget('CINEMATIC', 'full', false, 'NORMAL') === 64, 'NORMAL CINEMATIC 64');
ok(E.particleBudget('CINEMATIC', 'full', false, 'REDUCED') < 64, 'REDUCED 降粒子');
ok(E.particleBudget('CINEMATIC', 'full', false, 'LOW') < E.particleBudget('CINEMATIC', 'full', false, 'REDUCED'), 'LOW 再降');
ok(E.particleBudget('CINEMATIC', 'full', false, 'CRITICAL') === 0, 'CRITICAL 0 粒子');
ok(E.particleBudget('HIGH', 'reduced', false, 'LOW') <= C.MAX_PARTICLE_BUDGET, '粒子上限');
ok(E.particleBudget('LOW', 'full', false, 'NORMAL') === 0, 'LOW 强度 0 粒子');
ok(E.particleBudget('CINEMATIC', 'full', true, 'NORMAL') === 0, 'Reduced Motion 0 粒子');
console.log('=== 5. Flash Safety / 强度 ===');
const flash = C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'];
const normalFlash = E.triggerVisualEffect(E.createVisualRuntime(0), flash, 0, { intensity: 'CINEMATIC', performanceMode: 'NORMAL' }).state.active[0];
const lowFlash = E.triggerVisualEffect(E.createVisualRuntime(0), flash, 0, { intensity: 'CINEMATIC', performanceMode: 'LOW' }).state.active[0];
const criticalFlash = E.triggerVisualEffect(E.createVisualRuntime(0), flash, 0, { intensity: 'CINEMATIC', performanceMode: 'CRITICAL' }).state.active[0];
ok(normalFlash.intensity > lowFlash.intensity, 'LOW 降低 Flash');
ok(criticalFlash.intensity === 0, 'CRITICAL 关闭 Flash');
const shake = C.BOSS_VISUAL_EFFECTS['boss-attack-impact'];
ok(E.triggerVisualEffect(E.createVisualRuntime(0), shake, 0, { intensity: 'CINEMATIC', performanceMode: 'CRITICAL' }).state.active[0].intensity === 0, 'CRITICAL 关闭 Shake');
const glitch = C.BOSS_VISUAL_EFFECTS['boss-crisis-glitch'];
ok(E.triggerVisualEffect(E.createVisualRuntime(0), glitch, 0, { intensity: 'CINEMATIC', performanceMode: 'CRITICAL' }).state.active[0].intensity === 0, 'CRITICAL 关闭 Glitch');
const reducedFlash = E.triggerVisualEffect(E.createVisualRuntime(0), flash, 0, { intensity: 'CINEMATIC', reducedMotion: true }).state.active[0];
ok(reducedFlash.intensity < 0.5, 'Reduced Motion 降低 Flash');
console.log('=== 6. Hard limits / Queue / Terminal ===');
let many = E.createVisualRuntime(0);
for (let i = 0; i < 20; i++) many = E.triggerVisualEffect(many, { ...C.BOSS_VISUAL_EFFECTS['boss-particle-stream'], effectId: 'b67-stress-' + i, duration: 500, queueable: true }, i).state;
ok(many.active.length <= C.MAX_ACTIVE_EFFECTS, 'Active 上限');
ok(many.queued.length <= C.MAX_QUEUED_EFFECTS, 'Queue 上限');
ok(E.particleBudget('CINEMATIC', 'full', false, 'NORMAL') <= C.MAX_PARTICLE_BUDGET, 'Hard particle limit');
const term = E.triggerVisualEffect(many, C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 30);
ok(term.state.active.some(e => e.effectId === 'boss-terminal-cinematic'), 'Terminal 可抢占压力队列');
ok(term.state.queued.length === 0, 'Terminal 清空队列');
const late = E.triggerVisualEffect(term.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 40);
ok(!late.state.active.some(e => e.effectId === 'boss-phase-cinematic'), 'Terminal P0 后不复活');
console.log('=== 7. Render cost / visibility ===');
ok(E.renderCostLevel('NORMAL', 2, 20) === 'MEDIUM', 'NORMAL 中成本');
ok(E.renderCostLevel('NORMAL', 5, 50) === 'HIGH', 'NORMAL 高成本');
ok(E.renderCostLevel('LOW', 3, 8) === 'LOW', 'LOW 低成本');
ok(E.renderCostLevel('CRITICAL', 6, 64) === 'LOW', 'CRITICAL 低成本');
ok(E.visualsPaused(true, false) && E.visualsPaused(false, true) && !E.visualsPaused(false, false), 'Page Visibility 暂停');
console.log('=== 8. Settings persistence ===');
const store = {};
globalThis.localStorage = { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = String(v); }, removeItem: k => { delete store[k]; } };
C.savePerformanceMode('LOW');
ok(store[C.PERFORMANCE_MODE_STORAGE_KEY] === 'LOW', 'Performance Mode 持久化');
C.saveVisualIntensity('HIGH');
ok(store[C.VISUAL_INTENSITY_STORAGE_KEY] === 'HIGH', 'Visual Intensity 持久化');
ok(C.performanceModeFromStorage('CRITICAL') === 'CRITICAL' && C.performanceModeFromStorage('bad') === 'AUTO', '读取自愈');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
