// V1.3-B.6.6 集成：真实 B.1 终结事件 → 视觉映射 / 结算只读
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const T = L('src/game/bossTerminalCinematicConfig.ts');
const Phase = L('src/game/bossPhaseEngine.ts');
const Plans = L('src/game/bossPhasePlans.ts');
const Arbiter = L('src/game/combatEventArbiter.ts');
const Save = L('src/services/save.ts');
const Settlement = L('src/game/bossSettlement.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 900000;
const plan = Plans.buildBossPhasePlan('gate-01', 'easy');
const makeRun = (id) => Phase.activateBattle(Phase.prepareBattle(Phase.createBossPhaseRun(plan, NOW, { battleId: id, hp: plan.totalHp }), NOW).run, plan, NOW).run;
console.log('=== 1. 真实 Victory ===');
const vRun = makeRun('term-victory');
const vStep = Phase.finishBattle(vRun, 'victory', NOW + 1000);
const vEvent = vStep.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.VICTORY);
ok(vStep.ok && !!vEvent, '真实 VICTORY 事件');
ok(vEvent.battleId === 'term-victory' && vEvent.bossId === 'gate-01' && !!vEvent.phaseId, '真实 battleId/bossId/phaseId');
ok(typeof vEvent.payload.hp === 'number', '真实 hp payload');
ok(T.terminalKindForEvent(vEvent.type, vEvent.payload) === 'victory', 'VICTORY → victory');
const vSnap = T.terminalSnapshotOf(vEvent.type, vEvent.payload, { battleId: vEvent.battleId, eventId: vEvent.id, bossId: vEvent.bossId, phaseId: vEvent.phaseId });
ok(vSnap.battleId === 'term-victory' && vSnap.eventId === vEvent.id, 'Victory snapshot 真实 ID');
ok(vSnap.kind === 'victory' && T.terminalTotalDuration('victory') === 4800, 'Victory 演出时长');
console.log('=== 2. 真实 Defeat ===');
const dRun = makeRun('term-defeat');
const dStep = Phase.finishBattle(dRun, 'defeat', NOW + 2000);
const dEvent = dStep.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.DEFEAT);
ok(dStep.ok && !!dEvent, '真实 DEFEAT 事件');
ok(T.terminalKindForEvent(dEvent.type, dEvent.payload) === 'defeat', 'DEFEAT → defeat');
ok(T.terminalSnapshotOf(dEvent.type, dEvent.payload, { battleId: dEvent.battleId, eventId: dEvent.id, bossId: dEvent.bossId, phaseId: dEvent.phaseId }).kind === 'defeat', 'Defeat snapshot');
console.log('=== 3. 真实 Retreat / Interrupted ===');
const rRun = makeRun('term-retreat');
const rStep = Phase.interruptBattle(rRun, NOW + 3000, '玩家撤退');
const rEvent = rStep.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.INTERRUPTED);
ok(rStep.ok && !!rEvent, '真实 INTERRUPTED 事件');
ok(rEvent.payload.reason === '玩家撤退', '真实撤退 reason');
ok(T.terminalKindForEvent(rEvent.type, rEvent.payload) === 'retreat', '撤退 → retreat');
const iStep = Phase.interruptBattle(makeRun('term-interrupted'), NOW + 4000, 'external-signal');
const iEvent = iStep.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.INTERRUPTED);
ok(T.terminalKindForEvent(iEvent.type, iEvent.payload) === 'interrupted', '通用中断 → interrupted');
ok(T.terminalSnapshotOf(iEvent.type, iEvent.payload, { battleId: iEvent.battleId, eventId: iEvent.id, bossId: iEvent.bossId, phaseId: iEvent.phaseId }).kind === 'interrupted', 'Interrupted snapshot');
console.log('=== 4. 去重 / 陈旧 / 重复终结 ===');
const k1 = T.terminalDedupeKey(vEvent.battleId, vEvent.id);
ok(k1 === 'term-victory:' + vEvent.id, 'battleId:eventId');
ok(k1 !== T.terminalDedupeKey('other-battle', vEvent.id), '不同战斗不冲突');
ok(k1 !== T.terminalDedupeKey(vEvent.battleId, 'other-event'), '不同事件不冲突');
const repeat = Phase.finishBattle(vStep.run, 'victory', NOW + 5000);
ok(!repeat.ok && repeat.events.length === 0, '重复终结被真实引擎拒绝');
const repeatInterrupt = Phase.interruptBattle(rStep.run, NOW + 5000, '玩家撤退');
ok(repeatInterrupt.events.length === 0, '重复中断被真实引擎拒绝');
console.log('=== 5. 视觉只读 / 优先级 ===');
const beforeRun = JSON.stringify(vStep.run);
let vis = E.createVisualRuntime(NOW);
for (const kind of ['victory', 'defeat', 'retreat', 'interrupted']) {
  vis = E.interruptVisualEffect(vis, 'boss-terminal-cinematic', NOW);
  vis = E.triggerVisualEffect(vis, { ...C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], duration: T.terminalTotalDuration(kind) }, NOW, { intensity: 'HIGH' }).state;
}
ok(JSON.stringify(vStep.run) === beforeRun, '视觉不修改真实终结 run');
ok(vStep.run.status === 'victory' && vStep.run.battleResult === 'victory', '真实结果保持 victory');
let s = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-warning'], 0).state;
s = E.triggerVisualEffect(s, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 1).state;
const term = E.triggerVisualEffect(s, C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 2, { intensity: 'HIGH' });
ok(term.state.completed.some(e => e.effectId === 'boss-phase-cinematic'), 'Terminal P0 抢占 Phase P1');
ok(term.state.completed.some(e => e.effectId === 'boss-attack-warning'), 'Terminal P0 抢占 Attack');
const crisis = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 0).state;
const crisisTerm = E.triggerVisualEffect(crisis, C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 1);
ok(crisisTerm.state.completed.some(e => e.effectId === 'boss-crisis-cinematic'), 'Terminal 抢占 Crisis');
const weak = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0).state;
const weakTerm = E.triggerVisualEffect(weak, C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 1);
ok(weakTerm.state.completed.some(e => e.effectId === 'boss-weakness-cinematic'), 'Terminal 抢占 Weakness');
const late = E.triggerVisualEffect(weakTerm.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 5);
ok(!late.state.active.some(e => e.effectId === 'boss-phase-cinematic'), 'Terminal 后旧视觉不复活');
ok(Arbiter.COMBAT_PRIORITY.TERMINAL === 0 && Arbiter.COMBAT_PRIORITY.BATTLE_FLOW === 1, 'B.4 Terminal P0');
console.log('=== 6. 结算 / 归档 / 奖励只读 ===');
const p = Save.defaultState();
const pBefore = JSON.stringify(p);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 0);
ok(JSON.stringify(p) === pBefore, '视觉不改玩家/统计/奖励/成就/归档');
ok(Save.SAVE_VERSION === 10, '存档版本 v10');
ok(Settlement.buildBossSettlementData(p, 'term-victory', { now: NOW }) === null, '无真实终结数据时不伪造结算');
ok(JSON.stringify(p.progress.bossBattleArchive || {}) === JSON.stringify(pBefore ? JSON.parse(pBefore).progress.bossBattleArchive : {}), '归档不变');
ok(JSON.stringify(p.progress.bossBattleRewards || {}) === JSON.stringify(JSON.parse(pBefore).progress.bossBattleRewards), '奖励不变');
ok(JSON.stringify(p.progress.bossAchievements || {}) === JSON.stringify(JSON.parse(pBefore).progress.bossAchievements), '成就不变');
console.log('=== 7. 多终结 / 主题 / 性能 ===');
const themes = ['victory', 'defeat', 'retreat', 'interrupted'].map(k => T.terminalThemeFor(k).primary);
ok(new Set(themes).size === 4, '四种终结主题不同');
ok(C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'].priority === C.VISUAL_PRIORITY.terminal, 'P0 注册');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, '粒子上限');
ok(E.particleBudget('LOW', 'full', false) === 0, 'LOW 0 粒子');
const reduced = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-terminal-cinematic'], 0, { reducedMotion: true, intensity: 'HIGH' }).state;
ok(reduced.active[0].intensity < 0.5, 'Reduced Motion 降低强度');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
