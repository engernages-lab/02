// V1.3-B.6.3 阶段转换电影化配置/引擎单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const P = L('src/game/bossPhaseTransitionCinematicConfig.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const stages = P.PHASE_CINEMATIC_STAGES;
console.log('=== 1. 配置 / 阶段主题 ===');
ok(stages.length === 6, '六阶段演出配置');
ok(stages[0].stage === 'pre' && stages[stages.length - 1].stage === 'recovery', '阶段首尾完整');
ok(stages[0].startMs === 0 && stages[stages.length - 1].endMs === P.PHASE_CINEMATIC_TOTAL_MS, '时间线总长一致');
for (let i = 1; i < stages.length; i++) ok(stages[i].startMs === stages[i - 1].endMs, '阶段无空档：' + i);
ok(P.phaseStageForElapsed(0).stage === 'pre' && P.phaseStageForElapsed(500).stage === 'distortion', 'elapsed 阶段映射');
ok(P.phaseStageForElapsed(99999).stage === 'recovery', '超长 elapsed fallback');
ok(P.phaseTransitionThemeFor(0).primary !== P.phaseTransitionThemeFor(1).primary, '不同阶段主题色');
ok(P.phaseTransitionThemeFor(99).primary === P.phaseTransitionThemeFor(2).primary, '超出阶段 fallback');
ok(P.phaseRevealNumber(1) === 'PHASE 02', 'Phase 编号 1-based/两位');
ok(P.phaseRevealNumber(1, 3) === 'PHASE 02 / 03', '真实总阶段数展示');
ok(P.phaseRevealNumber(-9) === 'PHASE 01', '非法编号安全');
ok(C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'].priority === C.VISUAL_PRIORITY.phase, '阶段演出 P1');
ok(C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'].duration === P.PHASE_CINEMATIC_TOTAL_MS, '阶段演出时长');
ok(C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'].interruptible === false, '阶段终结不可被普通效果中断');
console.log('=== 2. 生命周期 / 优先级 / cleanup ===');
let s = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-warning'], 0, { intensity: 'HIGH' }).state;
const phase = E.triggerVisualEffect(s, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 10, { intensity: 'HIGH' });
ok(phase.accepted && phase.state.active.some(e => e.effectId === 'boss-phase-cinematic'), '阶段演出启动');
ok(phase.state.completed.some(e => e.effectId === 'boss-attack-warning' && e.status === 'interrupted'), '阶段抢占攻击预警');
ok(phase.state.cleanupCount >= 1, '抢占清理计数');
const dup = E.triggerVisualEffect(phase.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 20);
ok(!dup.accepted && dup.reason === 'duplicate', '重复 transition 拒绝');
const terminal = E.triggerVisualEffect(phase.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 30);
ok(terminal.state.active.some(e => e.effectId === 'boss-terminal-flash'), '终结 P0 抢占阶段');
ok(terminal.state.completed.some(e => e.effectId === 'boss-phase-cinematic' && e.status === 'interrupted'), '终结清理阶段演出');
const cleanup = E.cleanupAllVisualEffects(terminal.state, 40);
ok(cleanup.active.length === 0 && cleanup.queued.length === 0, 'Cleanup 后无残留');
ok(E.cleanupAllVisualEffects(cleanup, 50) === cleanup, '重复 cleanup 幂等');
// 连续阶段转换：同 P1 同组会排队，不无限增长
let seq = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 0).state;
const seq2 = E.triggerVisualEffect(seq, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 3000);
ok(!seq2.accepted || seq2.reason === 'duplicate', '同阶段演出去重/不并发');
console.log('=== 3. 强度 / Reduced / 性能 ===');
ok(E.particleBudget('LOW', 'full', false) === 0, 'LOW 阶段演出无粒子');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, 'CINEMATIC 不超粒子上限');
const reduced = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 0, { intensity: 'HIGH', reducedMotion: true }).state;
ok(reduced.active[0].intensity < 0.5, 'Reduced Motion 降低阶段演出强度');
const activeLimit = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 0).state;
ok(activeLimit.active.length <= C.MAX_ACTIVE_EFFECTS, '活动效果上限');
ok(E.evaluateVisualPerformance(20, 'full', 0, 5000) === 'minimal', '阶段演出性能降级');
ok(C.VISUAL_LAYER_Z.terminal > C.VISUAL_LAYER_Z.cinematic, '终结层级高于阶段演出');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
