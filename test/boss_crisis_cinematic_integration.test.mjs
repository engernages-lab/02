// V1.3-B.6.5 集成：真实动态事件引擎 → 危机视觉映射隔离
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const X = L('src/game/bossCrisisCinematicConfig.ts');
const Ev = L('src/game/eventEngine.ts');
const D = L('src/game/events/unknownIntrusion.ts');
const Arbiter = L('src/game/combatEventArbiter.ts');
const Phase = L('src/game/bossPhaseEngine.ts');
const Plans = L('src/game/bossPhasePlans.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
D.registerUnknownIntrusion();
const NOW = 800000;
const out = Ev.tryTrigger(Ev.EMPTY_SNAPSHOT, D.UNKNOWN_INTRUSION_ID, NOW, { data: D.defaultIntrusionData() });
ok(out.ok, '真实 unknown-intrusion 触发');
const ev = out.state;
ok(ev.defId === D.UNKNOWN_INTRUSION_ID && !!ev.id, '真实 defId / 实例 id');
ok(ev.status === 'presenting' && ev.activateAt === NOW + D.UNKNOWN_INTRUSION_DEF.presentDurationMs, '真实 presenting / activateAt');
ok(ev.deadlineAt === NOW + D.UNKNOWN_INTRUSION_DEF.presentDurationMs + D.UNKNOWN_INTRUSION_DEF.activeTimeoutMs, '真实 deadlineAt');
ok(ev.priority === D.UNKNOWN_INTRUSION_DEF.priority, '真实优先级');
ok(ev.data.step === 0 && ev.data.missesLeft === 3, '真实初始 step/misses');
const snapPresenting = X.crisisSnapshotOf(ev, 'battle-crisis');
const tStart = X.crisisTransitions(null, snapPresenting);
ok(tStart.length === 1 && tStart[0].kind === 'warning', '真实触发 → Warning');
console.log('=== 1. 真实 presenting → active ===');
const snapActiveEv = Ev.advance({ current: ev, cooldowns: out.snapshot.cooldowns }, NOW + 1700).current;
ok(snapActiveEv.status === 'active', '真实 presenting → active');
const snapActive = X.crisisSnapshotOf(snapActiveEv, 'battle-crisis');
const tActive = X.crisisTransitions(snapPresenting, snapActive);
ok(tActive.length === 1 && tActive[0].kind === 'identification', 'active → Identification');
ok(tActive.every(t => t.kind !== 'escalation'), '真实流程不伪造 Escalation');
console.log('=== 2. 真实玩家步骤 / 失误 ===');
const stepEv = { ...snapActiveEv, data: { step: 1, missesLeft: 3 } };
const tStep = X.crisisTransitions(snapActive, X.crisisSnapshotOf(stepEv, 'battle-crisis'));
ok(tStep[0].kind === 'response' && tStep[0].detail.includes('1 / 3'), '真实 step → Response');
const missEv = { ...stepEv, data: { step: 1, missesLeft: 2 } };
const tMiss = X.crisisTransitions(X.crisisSnapshotOf(stepEv, 'battle-crisis'), X.crisisSnapshotOf(missEv, 'battle-crisis'));
ok(tMiss[0].kind === 'impact' && tMiss[0].detail.includes('2 / 3'), '真实 miss → Impact');
console.log('=== 3. 真实完成 / 取消 / 异常恢复 ===');
const resolved = Ev.resolve({ current: missEv, cooldowns: {} }, NOW + 5000);
ok(resolved.current.status === 'completed' && resolved.current.result === 'completed', '真实 resolve → completed');
const tDone = X.crisisTransitions(X.crisisSnapshotOf(missEv, 'battle-crisis'), X.crisisSnapshotOf(resolved.current, 'battle-crisis'));
ok(tDone[0].kind === 'resolution', '真实完成 → Resolution');
const dismissed = Ev.dismiss(resolved);
ok(dismissed.current === null, '真实 dismiss → null');
const tDismiss = X.crisisTransitions(X.crisisSnapshotOf(resolved.current, 'battle-crisis'), X.crisisSnapshotOf(dismissed.current, 'battle-crisis'));
ok(tDismiss[0].kind === 'recovery', '真实 dismiss → Recovery');
const cancelled = Ev.cancelEvent({ current: missEv, cooldowns: {} }, NOW + 6000);
const tCancel = X.crisisTransitions(X.crisisSnapshotOf(missEv, 'battle-crisis'), X.crisisSnapshotOf(cancelled.current, 'battle-crisis'));
ok(cancelled.current.result === 'cancelled' && tCancel[0].kind === 'recovery', '真实取消 → Recovery');
const recovered = Ev.recoverException({ current: missEv, cooldowns: {} }, NOW + 7000);
const tRecover = X.crisisTransitions(X.crisisSnapshotOf(missEv, 'battle-crisis'), X.crisisSnapshotOf(recovered.current, 'battle-crisis'));
ok(recovered.current.result === 'recovered' && tRecover[0].kind === 'recovery', '真实异常恢复 → Recovery');
console.log('=== 4. 真实超时 ===');
const timeoutSnap = Ev.advance({ current: { ...snapActiveEv, status: 'active' }, cooldowns: {} }, NOW + D.UNKNOWN_INTRUSION_DEF.presentDurationMs + D.UNKNOWN_INTRUSION_DEF.activeTimeoutMs + 1);
ok(timeoutSnap.current.status === 'resolving' && timeoutSnap.current.result === 'timeout', '真实超时 → resolving(timeout)');
const tTimeout = X.crisisTransitions(snapActive, X.crisisSnapshotOf(timeoutSnap.current, 'battle-crisis'));
ok(tTimeout.length === 2 && tTimeout[0].kind === 'impact' && tTimeout[1].kind === 'recovery', '真实超时 → Impact + Recovery');
console.log('=== 5. 重复触发 / 冷却 / 互斥 ===');
const dup = Ev.tryTrigger({ current: ev, cooldowns: {} }, D.UNKNOWN_INTRUSION_ID, NOW + 100);
ok(!dup.ok && dup.reason === 'already-presenting', '展示中重复触发拒绝');
Ev.registerEvent({ id: 'test-other-crisis', label: 'test', priority: 90, mutualExclude: [], cooldownMs: 0, presentDurationMs: 100, activeTimeoutMs: 1000 });
const mutex = Ev.tryTrigger({ current: ev, cooldowns: {} }, 'test-other-crisis', NOW + 100);
ok(!mutex.ok && mutex.reason === 'mutex', '不同危机互斥');
const cooldown = Ev.tryTrigger({ current: null, cooldowns: out.snapshot.cooldowns }, D.UNKNOWN_INTRUSION_ID, NOW + 1000);
ok(!cooldown.ok && cooldown.reason === 'cooldown', '真实冷却生效');
ok(Ev.isBlocking(ev) && !Ev.isBlocking(resolved.current) && !Ev.isBlocking(null), '真实 blocking 语义');
console.log('=== 6. battle 隔离 / 陈旧事件 ===');
const otherBattle = { ...snapActive, battleId: 'battle-other' };
ok(X.crisisTransitions(snapActive, otherBattle).length === 0, '不同 battleId 状态差异拒绝');
ok(X.crisisTransitions(snapPresenting, { ...snapPresenting, battleId: 'battle-other' }).length === 0, '旧战斗 snapshot 拒绝');
ok(X.crisisSnapshotOf(null, 'battle-crisis') === null, '空危机不生成快照');
console.log('=== 7. 视觉只读 / 优先级 / 终结 ===');
const beforeEv = JSON.stringify({ current: snapActiveEv, cooldowns: out.snapshot.cooldowns });
let vis = E.createVisualRuntime(NOW);
for (const kind of ['warning', 'detection', 'identification', 'escalation', 'impact', 'response', 'resolution', 'recovery']) {
  const stage = X.crisisCinematicStageFor(kind);
  vis = E.interruptVisualEffect(vis, 'boss-crisis-cinematic', NOW);
  vis = E.triggerVisualEffect(vis, { ...C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], duration: stage.durationMs }, NOW, { intensity: 'HIGH' }).state;
}
ok(JSON.stringify({ current: snapActiveEv, cooldowns: out.snapshot.cooldowns }) === beforeEv, '视觉演出不修改真实事件状态');
let s = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0).state;
const crisis = E.triggerVisualEffect(s, C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 5, { intensity: 'HIGH' });
ok(crisis.state.completed.some(e => e.effectId === 'boss-weakness-cinematic'), 'Crisis P2 抢占 Weakness P3');
const phaseVisual = E.triggerVisualEffect(crisis.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 10);
ok(phaseVisual.state.completed.some(e => e.effectId === 'boss-crisis-cinematic'), 'Phase P1 抢占 Crisis P2');
const terminalVisual = E.triggerVisualEffect(phaseVisual.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 15);
ok(terminalVisual.state.completed.some(e => e.effectId === 'boss-phase-cinematic'), 'Terminal P0 抢占 Phase');
ok(Arbiter.COMBAT_PRIORITY.CRISIS < Arbiter.COMBAT_PRIORITY.WEAKNESS && Arbiter.COMBAT_PRIORITY.WEAKNESS < Arbiter.COMBAT_PRIORITY.ATTACK, 'B.4 P2 < P3 < P5');
ok(Arbiter.COMBAT_PRIORITY.TERMINAL < Arbiter.COMBAT_PRIORITY.CRISIS && Arbiter.COMBAT_PRIORITY.BATTLE_FLOW < Arbiter.COMBAT_PRIORITY.CRISIS, 'B.4 P0/P1 < P2');
const plan = Plans.buildBossPhasePlan('gate-01', 'easy');
const run = Phase.activateBattle(Phase.prepareBattle(Phase.createBossPhaseRun(plan, NOW, { battleId: 'crisis-battle', hp: plan.totalHp }), NOW).run, plan, NOW).run;
const trans = Phase.evaluatePhaseTransition(run, plan, { hp: Math.floor(plan.totalHp * 0.5), completedChallenges: [] }, NOW + 1000);
ok(!!trans.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.PHASE_TRANSITION), '真实阶段转换事件可用于 P1 抢占');
console.log('=== 8. 存档 / 经济 / 统计 ===');
ok(Save.SAVE_VERSION === 10, '存档版本 v10');
const p = Save.defaultState();
const pBefore = JSON.stringify(p);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'], 0);
ok(JSON.stringify(p) === pBefore, '视觉演出不改存档/经济/统计');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, '粒子上限');
ok(C.BOSS_VISUAL_EFFECTS['boss-crisis-cinematic'].priority === C.VISUAL_PRIORITY.crisis, '危机视觉 P2');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
