// V1.3-E 玩家成长 / 风险单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const G = L('src/game/playerGrowthCore.ts');
const P = L('src/game/progression.ts');
const A = L('src/game/achievements.ts');
const E = L('src/game/explorationCore.ts');
const M = L('src/game/miraCore.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 1000;
console.log('=== 1. 等级 / 经验 ===');
ok(P.LEVEL_XP[0] === 0 && P.LEVEL_XP[1] === 100 && P.LEVEL_XP.length === 10, '真实等级阈值');
ok(P.levelForExp(0) === 1 && P.levelForExp(99) === 1 && P.levelForExp(100) === 2, 'Lv1/Lv2 阈值');
ok(P.levelForExp(99999) === 10 && P.MAX_LEVEL === 10, '等级上限 Lv10');
ok(P.titleForLevel(1) === '见习硅灵' && P.titleForLevel(10) === '原初继承者', '真实称号');
ok(P.toleranceFor(1) === 3 && P.toleranceFor(3) === 4 && P.toleranceFor(5) === 5 && P.toleranceFor(9) === 7, '等级容错');
const ms = P.milestone(150);
ok(ms.level === 2 && ms.into === 50 && ms.need === 160 && ms.maxed === false, '经验里程碑');
ok(P.milestone(3000).maxed === true, '满级里程碑');
console.log('=== 2. 风险状态 ===');
const normal = G.riskStatusFor({ consciousness: 100, level: 1 });
ok(normal.level === 'NORMAL' && normal.toleranceRemaining === 3, '正常状态');
ok(G.riskStatusFor({ consciousness: 50, level: 1 }).level === 'WARNING', '意识/容错预警');
ok(G.riskStatusFor({ consciousness: 30, level: 1 }).level === 'DANGER', '意识危险');
ok(G.riskStatusFor({ consciousness: 10, level: 1 }).level === 'CRITICAL', '意识危急');
ok(G.riskStatusFor({ consciousness: 100, level: 1, failures: 1 }).level === 'WARNING', '失败 2 次前预警');
ok(G.riskStatusFor({ consciousness: 100, level: 1, failures: 2 }).level === 'DANGER', '剩余容错 1 → DANGER');
ok(G.riskStatusFor({ consciousness: 100, level: 1, failures: 3 }).level === 'CRITICAL', '容错耗尽 → CRITICAL');
ok(G.RISK_META.CRITICAL.color === '#FF5B64' && !!G.RISK_META.NORMAL.hint, '风险视觉 metadata');
console.log('=== 3. 成长总览 ===');
let p = Save.defaultState();
p.exp = 150;
p.level = P.levelForExp(p.exp);
const ex = E.defaultExplorationState(NOW);
let st = E.discoverRegion(ex, 'training', NOW).state;
for (const id of ['signal:training', 'ruin:training']) st = E.completeExploreNode(st, 'training', id, ['training'], NOW).state;
const term = E.startTerminalChallenge(st, 'training', 'terminal:training', NOW);
st = E.completeTerminalChallenge(term.state, 'tut-1', true, NOW).state;
st = E.completeExploreNode(st, 'training', 'hidden:training:echo', ['training'], NOW).state;
p.progress = { ...p.progress, exploration: st, unlockedServers: ['training', 'syntax'], stars: { 'tut-1': 3 } };
p.mira = M.normalizeMiraState({ exp: 81 }, NOW);
const ov = G.growthOverviewFor({ ...p, exp: 150, level: 2 }, 26);
ok(ov.level === 2 && ov.title === '初级硅灵' && ov.pct >= 0 && ov.pct <= 100, '成长总览等级/进度');
ok(ov.completedChallenges === 0 && ov.totalChallenges === 26, '挑战统计');
ok(ov.regionsUnlocked === 2 && ov.regionsCompleted === 1 && ov.explorePct > 0, '探索统计');
ok(ov.achievementCount === 0, '成就统计来自真实数据');
ok(ov.miraLevel >= 3, 'MIRA 等级统计');
console.log('=== 4. 成就联动 ===');
const all = A.recalcAchievements(p);
ok(all.includes('explorer_first'), '完成区域 → 探索者');
ok(all.includes('hidden_signal'), '隐藏信号 → 数据追踪者');
const crisisP = { ...p, mira: M.normalizeMiraState({ memories: { 'mira-major-crisis': { unlockedAt: NOW, read: false } } }, NOW) };
ok(A.recalcAchievements(crisisP).includes('crisis_handler'), '真实危机完成 → 危机处理者');
const again = A.recalcAchievements({ ...p, progress: { ...p.progress, achievements: all } });
ok(again.length === all.length, '重复重算不重复成就');
ok(A.ACHIEVEMENTS.filter(x => ['explorer_first', 'hidden_signal', 'crisis_handler'].includes(x.id)).length === 3, '新增 3 个探索/危机成就');
console.log('=== 5. 存档 / 兼容 ===');
ok(Save.SAVE_VERSION === 10, 'SAVE_VERSION 10');
ok(Save.defaultState().progress.exploration && Save.defaultState().mira, '默认包含探索/MIRA');
const norm = Save.normalizePlayerState({ ...p, progress: { ...p.progress, exploration: undefined } }, 10);
ok(!!norm.progress.exploration && norm.level === p.level, '缺失探索安全初始化');
const risk = G.riskStatusFor({ consciousness: 100, level: norm.level });
ok(risk.toleranceMax === P.toleranceFor(norm.level), '风险容错读取等级');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
