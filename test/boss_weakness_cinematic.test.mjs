// V1.3-B.6.4 弱点电影化配置/视觉引擎单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const W = L('src/game/bossWeaknessCinematicConfig.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const kinds = ['scan', 'discovery', 'crack', 'break', 'expose', 'recovery'];
const stages = W.WEAKNESS_CINEMATIC_STAGES;
console.log('=== 1. 配置 / 阶段 ===');
ok(stages.length === 6, '六阶段演出配置');
ok(kinds.every((k, i) => stages[i].kind === k), '演出顺序 scan→discovery→crack→break→expose→recovery');
ok(stages.every(s => s.durationMs > 0), '每阶段时长有效');
ok(stages.every(s => !!s.kicker && !!s.label && !!s.text), '阶段文案完整');
ok(stages[2].durationMs === 1400 && stages[3].durationMs === 1600, 'Crack/Break 时长配置');
ok(W.weaknessCinematicStageFor('scan').kind === 'scan', 'stage lookup');
ok(W.weaknessCinematicStageFor('nope').kind === 'discovery', 'stage 非法 fallback');
console.log('=== 2. 主题 ===');
for (const k of kinds) {
  const t = W.weaknessCinematicThemeFor(k);
  ok(/^#[0-9a-fA-F]{3,8}$/.test(t.primary) && /^#[0-9a-fA-F]{3,8}$/.test(t.secondary) && /^#[0-9a-fA-F]{3,8}$/.test(t.danger), '主题颜色合法：' + k);
}
ok(W.weaknessCinematicThemeFor('scan').primary !== W.weaknessCinematicThemeFor('crack').primary, '不同阶段主题不同');
const bad = W.weaknessCinematicThemeFor('recovery', { primaryColor: 'red', secondaryColor: 'NaN', dangerColor: '#GGG' });
ok(bad.primary === '#42D6D0' && bad.secondary === '#8FA6B2' && bad.danger === '#FF5B64', '非法 Boss 主题安全 fallback');
const bossTheme = W.weaknessCinematicThemeFor('recovery', { primaryColor: '#00E5FF', secondaryColor: '#7B61FF' });
ok(bossTheme.primary === '#00E5FF' && bossTheme.secondary === '#7B61FF', 'Recovery 使用真实 Boss 主题色');
console.log('=== 3. 真实事件映射 ===');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_HINT', { phase: 'analyzing' }) === 'scan', 'HINT(analyzing) → scan');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_HINT', { text: 'clue' }) === null, '普通线索 HINT 不播放完整演出');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_ANALYZED') === null, 'ANALYZED 不重复播放');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_DISCOVERED') === 'discovery', 'DISCOVERED → discovery');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_CHALLENGE_STARTED') === 'crack', 'CHALLENGE_STARTED → crack');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_CHALLENGE_SUCCESS') === 'break', 'CHALLENGE_SUCCESS → break');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_CHALLENGE_FAILED') === null, 'CHALLENGE_FAILED 无 break 演出');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_EXPOSED') === 'expose', 'EXPOSED → expose');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_EFFECT_APPLIED') === null, 'EFFECT_APPLIED 去重不演出');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_RECOVERED') === 'recovery', 'RECOVERED → recovery');
ok(W.weaknessCinematicKindForEvent('BOSS_WEAKNESS_CANCELLED') === null, 'CANCELLED 仅清理');
ok(W.weaknessCinematicKindForEvent('UNKNOWN', null) === null, '未知事件安全');
console.log('=== 4. 去重键 ===');
const k1 = W.weaknessCinematicDedupeKey('battle-1', 'gate-01-w1', 'evt-1');
ok(k1 === 'battle-1:gate-01-w1:evt-1', 'battleId:weaknessId:eventId');
ok(k1 !== W.weaknessCinematicDedupeKey('battle-2', 'gate-01-w1', 'evt-1'), '不同战斗不冲突');
ok(k1 !== W.weaknessCinematicDedupeKey('battle-1', 'gate-01-w2', 'evt-1'), '同名不同弱点不冲突');
ok(k1 !== W.weaknessCinematicDedupeKey('battle-1', 'gate-01-w1', 'evt-2'), '同弱点不同事件不冲突');
ok(W.weaknessCinematicDedupeKey(null, null, null) === '::', '空值安全');
console.log('=== 5. 视觉注册 / 优先级 ===');
const def = C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'];
ok(!!def, '弱点演出注册');
ok(def.priority === C.VISUAL_PRIORITY.weakness, '弱点演出 P3');
ok(def.queueable === false, '弱点演出不排队');
ok(def.interruptible === true, '弱点演出可被 P1/P0 中断');
ok(def.duration === 1600, '默认时长与 Break 阶段一致');
ok(def.layer === 'cinematic', '弱点演出 cinematic 层');
console.log('=== 6. 生命周期 / 抢占 / 清理 ===');
let st = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-warning'], 0, { intensity: 'HIGH' }).state;
const weak = E.triggerVisualEffect(st, C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 10, { intensity: 'HIGH' });
ok(weak.accepted && weak.state.active.some(e => e.effectId === 'boss-weakness-cinematic'), '弱点演出启动');
ok(weak.state.completed.some(e => e.effectId === 'boss-attack-warning' && e.status === 'interrupted'), '弱点演出抢占攻击预警');
ok(weak.state.cleanupCount >= 1, '抢占清理计数');
const dup = E.triggerVisualEffect(weak.state, C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 20);
ok(!dup.accepted && dup.reason === 'duplicate', '重复弱点演出拒绝');
const phase = E.triggerVisualEffect(weak.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 30);
ok(phase.state.active.some(e => e.effectId === 'boss-phase-cinematic'), 'P1 阶段演出抢占弱点');
ok(phase.state.completed.some(e => e.effectId === 'boss-weakness-cinematic' && e.status === 'interrupted'), '阶段演出清理弱点');
const terminal = E.triggerVisualEffect(phase.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 40);
ok(terminal.state.active.some(e => e.effectId === 'boss-terminal-flash'), 'P0 终结抢占阶段/弱点');
const cleaned = E.cleanupAllVisualEffects(terminal.state, 50);
ok(cleaned.active.length === 0 && cleaned.queued.length === 0, 'Cleanup 后无残留');
ok(E.cleanupAllVisualEffects(cleaned, 60) === cleaned, '重复 cleanup 幂等');
console.log('=== 7. 强度 / 性能预算 ===');
ok(E.particleBudget('LOW', 'full', false) === 0, 'LOW 无粒子');
ok(E.particleBudget('CINEMATIC', 'full', false) <= C.MAX_PARTICLE_BUDGET, 'CINEMATIC 不超粒子上限');
const reduced = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0, { intensity: 'HIGH', reducedMotion: true }).state;
ok(reduced.active[0].intensity < 0.5, 'Reduced Motion 降低弱点演出强度');
ok(E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0).state.active.length <= C.MAX_ACTIVE_EFFECTS, '活动效果上限');
ok(E.evaluateVisualPerformance(20, 'full', 0, 5000) === 'minimal', '性能降级');
ok(C.VISUAL_LAYER_Z.terminal > C.VISUAL_LAYER_Z.cinematic, '终结层级高于弱点演出');
let many = E.createVisualRuntime(0);
for (let i = 0; i < 12; i++) {
  many = E.triggerVisualEffect(many, { ...C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], effectId: 'weak-' + i, priority: C.VISUAL_PRIORITY.ambient }, i).state;
}
ok(many.queued.length <= C.MAX_QUEUED_EFFECTS, '队列不超过上限');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
