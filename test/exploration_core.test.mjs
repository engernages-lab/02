// V1.3-D 数字世界探索核心单元测试
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const X = L('src/game/explorationCore.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 1000;
const regions = X.explorationRegionDefs();
const training = X.explorationRegionDef('training');
console.log('=== 1. 区域 / 节点 ===');
ok(regions.length === 7, '复用七个服务器区域');
ok(regions.every(r => r.nodes.filter(n => n.kind !== 'hidden').length === 3), '每区域 3 个核心节点');
ok(regions.some(r => r.nodes.some(n => n.kind === 'ruin' && n.name === '初代核心档案')), '遗迹一：初代核心档案');
ok(regions.some(r => r.nodes.some(n => n.kind === 'ruin' && r.id === 'syntax')), '遗迹二：语法区域被封锁节点');
ok(training.nodes.some(n => n.kind === 'hidden' && n.id === 'hidden:training:echo'), '隐藏事件 hidden_signal_echo');
ok(training.nodes.find(n => n.kind === 'terminal')?.levelId === 'tut-1', '终端绑定真实关卡');
console.log('=== 2. 解锁 / 状态 ===');
const locked = X.regionStatus(X.defaultExplorationState(NOW), 'syntax', ['training']);
ok(locked === 'LOCKED', '未解锁区域 LOCKED');
const avail = X.regionStatus(X.defaultExplorationState(NOW), 'training', ['training']);
ok(avail === 'AVAILABLE', '训练区域 AVAILABLE');
let st = X.defaultExplorationState(NOW);
let d = X.discoverRegion(st, 'training', NOW);
st = d.state;
ok(d.changed && X.regionStatus(st, 'training', ['training']) === 'ABNORMAL', '发现信号 → ABNORMAL');
ok(X.nodeState(st, 'signal:training') === 'discovered', '信号已发现');
console.log('=== 3. 探索事件 / 幂等 ===');
let r = X.completeExploreNode(st, 'training', 'signal:training', ['training'], NOW + 1);
st = r.state;
ok(r.changed && r.firstTime && r.credits === 5, '信号调查完成 +5');
ok(X.nodeState(st, 'signal:training') === 'completed', '信号节点完成');
const dup = X.completeExploreNode(st, 'training', 'signal:training', ['training'], NOW + 2);
ok(!dup.changed && !dup.firstTime, '重复调查不重复领奖');
ok(st.rewardsClaimed.filter(x => x === 'signal:training').length === 1, '奖励 ID 幂等');
ok(st.archive.some(a => a.id === 'signal:training'), '探索档案记录');
console.log('=== 4. 遗迹 ===');
r = X.completeExploreNode(st, 'training', 'ruin:training', ['training'], NOW + 3);
st = r.state;
ok(r.changed && r.firstTime && r.credits === 8, '遗迹调查完成 +8');
ok(st.ruins['ruin:training'], '遗迹状态保存');
ok(!X.completeExploreNode(st, 'training', 'ruin:training', ['training'], NOW + 4).changed, '遗迹重复不重复领奖');
console.log('=== 5. 真实终端挑战 ===');
const start = X.startTerminalChallenge(st, 'training', 'terminal:training', NOW + 5);
ok(start.pending?.levelId === 'tut-1', '终端进入真实 tut-1 挑战');
const fail = X.completeTerminalChallenge(start.state, 'tut-1', false, NOW + 6);
ok(!fail.changed && fail.state.pendingChallenge === null, '挑战失败不完成节点');
const start2 = X.startTerminalChallenge(fail.state, 'training', 'terminal:training', NOW + 7);
const win = X.completeTerminalChallenge(start2.state, 'tut-1', true, NOW + 8);
st = win.state;
ok(win.changed && win.credits === 10, '真实挑战成功完成终端 +10');
ok(X.nodeState(st, 'terminal:training') === 'completed', '终端节点完成');
ok(!X.completeTerminalChallenge(st, 'tut-1', true, NOW + 9).changed, '重复完成不重复奖励');
console.log('=== 6. 区域完成 / 隐藏事件 ===');
ok(X.regionCompleted(st, 'training'), '训练区域核心完成');
ok(X.regionProgress(st, 'training').pct === 100, '区域进度 100%');
ok(X.hiddenAvailable(st, 'training'), '满足条件隐藏信号出现');
ok(!X.hiddenAvailable(X.defaultExplorationState(NOW), 'training'), '未完成区域隐藏事件不可触发');
const hidden = X.completeExploreNode(st, 'training', 'hidden:training:echo', ['training'], NOW + 10);
st = hidden.state;
ok(hidden.changed && hidden.firstTime && hidden.credits === 20, '隐藏信号奖励 +20');
ok(st.hidden['hidden:training:echo'], '隐藏档案记录');
ok(!X.completeExploreNode(st, 'training', 'hidden:training:echo', ['training'], NOW + 11).changed, '隐藏事件幂等');
console.log('=== 7. 危险 / 统计 ===');
ok(X.regionDangerLabel(1) === 'LOW' && X.regionDangerLabel(2) === 'MEDIUM' && X.regionDangerLabel(3) === 'HIGH', '危险等级标签');
const totals = X.explorationTotals(st, ['training']);
ok(totals.regionsUnlocked === 1 && totals.regionsCompleted === 1, '统计区域');
ok(totals.nodesCompleted === 3 && totals.nodesTotal === 21, '统计节点（已解锁/全部）');
ok(totals.ruinsCompleted === 1 && totals.hiddenFound === 1, '统计遗迹/隐藏');
ok(totals.pct > 0 && totals.pct <= 100, '总进度真实计算');
console.log('=== 8. 自愈 / 存档兼容 ===');
const corrupt = X.normalizeExplorationState({
  events: { 'signal:training': { status: 'completed', discoveredAt: 'x', completedAt: 1 }, bad: {} },
  rewardsClaimed: ['signal:training', 'signal:training'],
  hidden: { 'hidden:training:echo': { title: '回声', at: 1 }, bad: {} },
  pendingChallenge: { regionId: 'training', nodeId: 'signal:training', levelId: 'x' },
}, NOW);
ok(corrupt.events['signal:training']?.status === 'completed', '合法事件保留');
ok(!corrupt.events.bad, '非法事件清理');
ok(corrupt.rewardsClaimed.length === 1, '奖励 ID 去重');
ok(corrupt.pendingChallenge === null, '非法 pending 清理');
ok(X.normalizeExplorationState(null).version === 1, '缺失探索状态默认初始化');
const def = Save.defaultState();
ok(!!def.progress.exploration && def.progress.exploration.version === 1, 'defaultState 包含探索');
ok(Save.SAVE_VERSION === 10, 'SAVE_VERSION 10');
const old = { ...def, progress: { ...def.progress, exploration: undefined } };
const norm = Save.normalizePlayerState(old, 10);
ok(!!norm.progress.exploration && norm.level === def.level, '旧存档安全补齐探索字段');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
