// V1.3-B.6.4 集成：真实 B.3 弱点事件 → 视觉映射隔离
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const cache = new Map();
function load(file) {
  const abs = file;
  if (cache.has(abs)) return cache.get(abs).exports;
  const src = readFileSync(abs, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
  const mod = { exports: {} };
  cache.set(abs, mod);
  new Function('exports', 'module', 'require', out)(mod.exports, mod, (sp) => {
    const b = join(dirname(abs), sp);
    const c = existsSync(b) && extname(b) ? b : existsSync(b + '.ts') ? b + '.ts' : b + '/index.ts';
    return load(c);
  });
  return mod.exports;
}
const L = (rel) => load(join(root, rel));
const C = L('src/game/bossBattleVisualConfig.ts');
const E = L('src/game/bossBattleVisualEngine.ts');
const W = L('src/game/bossWeaknessCinematicConfig.ts');
const Weak = L('src/game/bossWeaknessEngine.ts');
const Catalog = L('src/game/bossWeaknessCatalog.ts');
const Plans = L('src/game/bossPhasePlans.ts');
const Phase = L('src/game/bossPhaseEngine.ts');
const Attack = L('src/game/bossAttackEngine.ts');
const Arbiter = L('src/game/combatEventArbiter.ts');
const Save = L('src/services/save.ts');
let pass = 0, total = 0;
const ok = (cond, label, extra = '') => { total++; if (cond) { pass++; console.log('PASS | ' + label); } else console.log('FAIL | ' + label + (extra ? '  => ' + extra : '')); };
const NOW = 500000;
const plan = Plans.buildBossPhasePlan('gate-01', 'easy');
const defs = Catalog.weaknessDefinitionsFor('gate-01', 'easy');
const def = Weak.definitionsForPhase(defs, 0)[0];
let run = Weak.createBossWeaknessRun('battle-b64', 'gate-01', plan.phases[0].phaseId, 0, defs, NOW);
console.log('=== 1. 真实线索 / 分析 / 发现 ===');
const clueEvents = [];
let step = Weak.observeWeakness(run, defs, { kind: 'attack-telegraph' }, NOW + 10);
run = step.state; clueEvents.push(...step.events);
step = Weak.observeWeakness(run, defs, { kind: 'attack-result', result: 'blocked' }, NOW + 20);
run = step.state; clueEvents.push(...step.events);
ok(clueEvents.every(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_HINT), '真实线索事件为 WEAKNESS_HINT');
ok(run.entries[def.weaknessId].clues.length >= def.requiredClues, '线索达到真实分析条件');
ok(run.entries[def.weaknessId].clues.length === def.requiredClues, '线索数量与真实配置一致');
const analysis = Weak.startAnalysis(run, defs, NOW + 30);
run = analysis.state;
const scanEvent = analysis.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_HINT && e.payload.phase === 'analyzing');
ok(!!scanEvent, '真实分析开始事件');
ok(W.weaknessCinematicKindForEvent(scanEvent.type, scanEvent.payload) === 'scan', '分析开始 → Scan');
ok(scanEvent.payload.analysisEndsAt === run.entries[def.weaknessId].analysisEndsAt, 'Scan 读取真实 analysisEndsAt');
const discovered = Weak.tickWeakness(run, defs, analysis.state.entries[def.weaknessId].analysisEndsAt);
run = discovered.state;
const discoveredEvent = discovered.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_DISCOVERED);
ok(!!discoveredEvent, '真实 WEAKNESS_DISCOVERED 事件');
ok(discoveredEvent.payload.name === def.name, '真实弱点名称');
ok(discoveredEvent.payload.weaknessType === def.weaknessType, '真实弱点类型');
ok(discoveredEvent.weaknessId === def.weaknessId && discoveredEvent.battleId === 'battle-b64', '真实 weaknessId / battleId');
ok(discoveredEvent.phaseId === plan.phases[0].phaseId, '真实 phaseId');
ok(W.weaknessCinematicKindForEvent(discoveredEvent.type, discoveredEvent.payload) === 'discovery', 'DISCOVERED → Discovery');
console.log('=== 2. 真实破解 / 击破 / 暴露 ===');
const begin = Weak.beginWeaknessCrack(run, defs, NOW + 2700);
run = begin.state;
const crackEvent = begin.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_CHALLENGE_STARTED);
ok(!!crackEvent && W.weaknessCinematicKindForEvent(crackEvent.type, crackEvent.payload) === 'crack', '真实破解开始 → Crack');
const complete = Weak.completeWeaknessCrack(run, defs, true, NOW + 3000);
run = complete.state;
const successEvent = complete.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_CHALLENGE_SUCCESS);
const exposeEvent = complete.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_EXPOSED);
const effectEvent = complete.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_EFFECT_APPLIED);
ok(!!successEvent && W.weaknessCinematicKindForEvent(successEvent.type, successEvent.payload) === 'break', '真实破解成功 → Break');
ok(!!exposeEvent && W.weaknessCinematicKindForEvent(exposeEvent.type, exposeEvent.payload) === 'expose', '真实 EXPOSED → Expose');
ok(!effectEvent || W.weaknessCinematicKindForEvent(effectEvent.type, effectEvent.payload) === null, 'EFFECT_APPLIED 不重复演出');
ok(exposeEvent.payload.damageMultiplier === def.damageMultiplier, 'Expose 读取真实伤害倍率');
ok(exposeEvent.payload.exposedUntil === run.entries[def.weaknessId].exposedUntil, 'Expose 读取真实暴露截止');
ok(run.entries[def.weaknessId].status === 'exposed', '真实状态 exposed');
ok(run.entries[def.weaknessId].successCount === 1, '真实成功次数 1');
const dupComplete = Weak.completeWeaknessCrack(run, defs, true, NOW + 3100);
ok(!dupComplete.changed && dupComplete.events.length === 0, '重复完成破解被真实引擎拒绝');
const exp = Weak.exposureInfo(run, defs, NOW + 3100);
ok(exp.active && exp.remainingMs > 0, '真实暴露窗口有效');
console.log('=== 3. 真实恢复 / 取消 ===');
const phaseSync = Weak.syncWeaknessPhase(run, defs, plan.phases[1].phaseId, 1, NOW + 20000);
const cancelEvent = phaseSync.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_CANCELLED);
ok(!!cancelEvent && cancelEvent.payload.reason === 'phase-change', '阶段切换真实取消旧弱点');
ok(!!cancelEvent && W.weaknessCinematicKindForEvent(cancelEvent.type, cancelEvent.payload) === null, 'CANCELLED 仅清理不演出');
const recovery = Weak.tickWeakness(run, defs, run.entries[def.weaknessId].exposedUntil + 1);
const recoverEvent = recovery.events.find(e => e.type === Weak.BOSS_BATTLE_EVENTS.WEAKNESS_RECOVERED);
ok(!!recoverEvent && W.weaknessCinematicKindForEvent(recoverEvent.type, recoverEvent.payload) === 'recovery', '真实 RECOVERED → Recovery');
ok(W.weaknessCinematicKindForEvent(Weak.BOSS_BATTLE_EVENTS.WEAKNESS_RECOVERED) === 'recovery', '恢复事件名称与配置一致');
console.log('=== 4. 视觉触发不改战斗 / 存档 ===');
const beforeRun = JSON.stringify(run);
let vis = E.createVisualRuntime(NOW);
for (const kind of ['scan', 'discovery', 'crack', 'break', 'expose', 'recovery']) {
  const stage = W.weaknessCinematicStageFor(kind);
  vis = E.interruptVisualEffect(vis, 'boss-weakness-cinematic', NOW);
  vis = E.triggerVisualEffect(vis, { ...C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], duration: stage.durationMs }, NOW, { intensity: 'HIGH' }).state;
}
ok(JSON.stringify(run) === beforeRun, '视觉演出不修改弱点状态');
ok(run.entries[def.weaknessId].status === 'exposed', '真实弱点状态保持 exposed');
const attack = Attack.createBossAttackState('battle-b64', 'gate-01', plan.phases[0].phaseId, 0, NOW);
const attackBefore = JSON.stringify(attack);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0);
ok(JSON.stringify(attack) === attackBefore, '视觉演出不修改攻击状态');
const p = Save.defaultState();
const pBefore = JSON.stringify(p);
E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 0);
ok(JSON.stringify(p) === pBefore, '视觉演出不改存档/统计/奖励');
ok(Save.SAVE_VERSION === 10, '存档版本保持 v10');
console.log('=== 5. 优先级 / 阶段 / 终结 / B.4 ===');
let s = E.triggerVisualEffect(E.createVisualRuntime(0), C.BOSS_VISUAL_EFFECTS['boss-attack-release'], 0).state;
const weak = E.triggerVisualEffect(s, C.BOSS_VISUAL_EFFECTS['boss-weakness-cinematic'], 10);
ok(weak.state.completed.some(e => e.effectId === 'boss-attack-release'), '弱点演出中断攻击 Release');
const phaseVisual = E.triggerVisualEffect(weak.state, C.BOSS_VISUAL_EFFECTS['boss-phase-cinematic'], 20);
ok(phaseVisual.state.completed.some(e => e.effectId === 'boss-weakness-cinematic'), 'Phase P1 抢占弱点');
const terminalVisual = E.triggerVisualEffect(phaseVisual.state, C.BOSS_VISUAL_EFFECTS['boss-terminal-flash'], 30);
ok(terminalVisual.state.completed.some(e => e.effectId === 'boss-phase-cinematic'), 'Terminal P0 抢占阶段');
ok(terminalVisual.state.active.some(e => e.effectId === 'boss-terminal-flash'), 'Terminal 视觉存在');
const trans = Phase.evaluatePhaseTransition(Phase.activateBattle(Phase.prepareBattle(Phase.createBossPhaseRun(plan, NOW, { battleId: 'b64-phase', hp: plan.totalHp }), NOW).run, plan, NOW).run, plan, { hp: Math.floor(plan.totalHp * 0.5), completedChallenges: [] }, NOW + 1000);
const transEvent = trans.events.find(e => e.type === Phase.BOSS_BATTLE_EVENTS.PHASE_TRANSITION);
ok(!!transEvent, '真实阶段转换事件存在');
ok(Arbiter.COMBAT_PRIORITY.WEAKNESS < Arbiter.COMBAT_PRIORITY.ATTACK, 'B.4 弱点优先于攻击');
ok(Arbiter.COMBAT_PRIORITY.TERMINAL < Arbiter.COMBAT_PRIORITY.WEAKNESS, 'B.4 终结优先于弱点');
ok(C.VISUAL_PRIORITY.phase < C.VISUAL_PRIORITY.weakness && C.VISUAL_PRIORITY.weakness < C.VISUAL_PRIORITY.attack, '视觉优先级 P1<P3<P4');
console.log('=== 6. 多 Boss / 多弱点 / 去重 ===');
const allIds = Plans.BOSS_PHASE_BOSS_IDS;
let multiOk = true;
for (const bossId of allIds) {
  const d = Catalog.weaknessDefinitionsFor(bossId, 'easy');
  if (!d.length || d.some(x => !x.name || !x.weaknessId || !x.bossId)) multiOk = false;
}
ok(multiOk, '全部 Boss 均有真实弱点配置');
const gateDefs = Catalog.weaknessDefinitionsFor('gate-01', 'expert');
ok(gateDefs.length >= 3, 'GATE-01 多阶段弱点');
const keys = new Set(gateDefs.map(d => W.weaknessCinematicDedupeKey('battle-b64', d.weaknessId, 'evt-1')));
ok(keys.size === gateDefs.length, '多弱点去重键互不冲突');
const kA = W.weaknessCinematicDedupeKey('battle-a', def.weaknessId, 'evt-1');
const kB = W.weaknessCinematicDedupeKey('battle-b', def.weaknessId, 'evt-1');
ok(kA !== kB, '旧 battleId 事件键不同');
console.log('\n结果：' + pass + ' / ' + total + ' 通过' + (pass === total ? ' ✅' : ' ❌'));
process.exit(pass === total ? 0 : 1);
